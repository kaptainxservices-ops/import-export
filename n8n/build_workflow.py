#!/usr/bin/env python3
"""Rewrite the workflow's trigger nodes from the list of collector mailboxes.

The number of collectors keeps moving — one, then five, then six — and every change
means new node ids, new positions and new connection entries. Editing that by hand is
how you end up with two nodes sharing a credential, which looks fine and silently means
two triggers watching one mailbox.

So MAILBOXES below is the input and `imap-to-ingest.json` is the output. Add a line,
re-run, re-import:

    python n8n/build_workflow.py

Everything downstream of the triggers is left exactly as it is — the Code nodes, the IF,
the HTTP request and their wiring are read from the file and written back untouched.
This only ever rewrites the IMAP triggers and the connections out of them, so it is safe
to run over a workflow you have edited in n8n and exported again.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

WORKFLOW = Path(__file__).resolve().parent / "imap-to-ingest.json"

IMAP = "n8n-nodes-base.emailReadImap"
FIRST_NODE = "Build the payload"

# (slug, the staff mailbox that forwards into this collector)
#
# The slug names the node and its credential, so keep it short and recognisable. The
# second column is documentation — it is what tells you, a year from now, whose mail
# stopped arriving when one trigger goes quiet.
MAILBOXES = [
    ("info", "info@tvdservices.com"),
    ("sales", "sales@tvdservices.com"),
    ("sales1", "sales1@tvdservices.com"),
    ("logistics", "tvdlogistics@outlook.com"),
    ("hotmail", "tvdservices@hotmail.com"),
    ("spare", "TODO: the sixth staff mailbox"),
]

PARAMETERS = {
    "mailbox": "INBOX",
    "postProcessAction": "read",
    "format": "resolved",
    "downloadAttachments": True,
    "options": {"customEmailConfig": '["UNSEEN"]', "forceReconnect": 60},
}

LEAD_NOTE = """IMAP with an app password, not the Gmail OAuth trigger.

gmail.readonly is a RESTRICTED scope: an External OAuth app needs Google verification \
plus an annual third-party CASA security assessment, and an app left in Testing mode \
expires its refresh token every 7 days. An app password on each collector avoids all of \
it.

format=resolved is required. The simple form drops attachments and the Message-ID, and \
Message-ID is what /ingest deduplicates on -- which matters because two staff mailboxes \
often forward the same supplier email, so it genuinely does arrive twice.

Each collector is its OWN trigger with its OWN credential. One mailbox per collector is \
the whole point: whoever can open a collector sees only what that one staff mailbox \
forwarded, not everyone's mail. One credential shared across nodes would mean several \
triggers watching the same inbox and the rest never read.

Generated by n8n/build_workflow.py -- add a mailbox there and re-run rather than copying \
a node by hand."""


def trigger(index: int, slug: str, forwarded_from: str) -> dict:
    return {
        "id": f"trigger-{slug}",
        "name": f"Collector: {slug}",
        "type": IMAP,
        "typeVersion": 2,
        "position": [-560, index * 180 - (len(MAILBOXES) - 1) * 90],
        "parameters": json.loads(json.dumps(PARAMETERS)),
        "alwaysOutputData": False,
        "credentials": {"imap": {"id": "REPLACE_ME", "name": f"Collector {slug} (IMAP)"}},
        "notes": (
            LEAD_NOTE
            if index == 0
            else f"Collector mailbox for {forwarded_from}. Its own IMAP credential, its "
            f"own app password. See the note on 'Collector: {MAILBOXES[0][0]}'."
        ),
    }


def main() -> int:
    flow = json.loads(WORKFLOW.read_text(encoding="utf-8"))

    slugs = [slug for slug, _ in MAILBOXES]
    if len(slugs) != len(set(slugs)):
        print("error: two mailboxes share a slug, so they would share a node name")
        return 1

    downstream = [n for n in flow["nodes"] if n["type"] != IMAP]
    if not any(n["name"] == FIRST_NODE for n in downstream):
        print(f"error: no {FIRST_NODE!r} node to connect the triggers to")
        return 1

    triggers = [trigger(i, slug, source) for i, (slug, source) in enumerate(MAILBOXES)]
    flow["nodes"] = triggers + downstream

    # Only the triggers' own connections are rewritten. Anything downstream keeps the
    # wiring it already had.
    connections = {
        name: value
        for name, value in flow["connections"].items()
        if not name.startswith("Collector: ") and name != "Watch the collector mailbox"
    }
    for node in triggers:
        connections[node["name"]] = {
            "main": [[{"node": FIRST_NODE, "type": "main", "index": 0}]]
        }
    flow["connections"] = connections

    WORKFLOW.write_text(json.dumps(flow, indent=2) + "\n", encoding="utf-8")

    print(f"{len(triggers)} collectors -> {FIRST_NODE}")
    for node in triggers:
        print(f"   {node['name']:<22} {node['credentials']['imap']['name']}")

    todo = [slug for slug, source in MAILBOXES if source.startswith("TODO")]
    if todo:
        print(f"\nstill unnamed: {', '.join(todo)} — rename the slug once you know the")
        print("mailbox, re-run, and name the n8n credential to match.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
